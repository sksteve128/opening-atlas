import { expect, test, vi } from 'vitest'
import { renderToStaticMarkup } from 'react-dom/server'

vi.mock('./StableBoard', () => ({ StableBoard: () => <div>Board</div> }))

test('Analysis keeps the board, playlist, unified Stockfish plans and explorer in one workspace', async () => {
  vi.stubGlobal('location', { href: 'http://localhost/?analysis=new', search: '?analysis=new' })
  vi.stubGlobal('window', { location: { href: 'http://localhost/?analysis=new' } })
  let savedSections: string | null = null
  vi.stubGlobal('localStorage', { getItem: (key: string) => key === 'opening-atlas-analysis-sections-v2' ? savedSections : null, setItem: vi.fn() })
  const { default: App, shouldRunPlanner } = await import('./App')
  expect(shouldRunPlanner(true, false, false, false)).toBe(true)
  expect(shouldRunPlanner(true, false, true, false)).toBe(false)
  expect(shouldRunPlanner(true, false, true, true)).toBe(true)
  expect(shouldRunPlanner(false, false, true, true)).toBe(false)
  expect(shouldRunPlanner(true, true, true, true)).toBe(false)
  const html = renderToStaticMarkup(<App />)
  const header = html.slice(html.indexOf('<header'), html.indexOf('</header>'))
  expect(header).toContain('class="header-generation"')
  expect(header).toContain('> Generate</button>')
  expect(header).toContain('aria-label="Generation options"')
  expect(header).toContain('class="generation-queue-anchor"')
  expect(header).toContain('aria-label="Settings"')
  expect(html.match(/> Generate<\/button>/g)).toHaveLength(1)
  expect(html).not.toContain('class="analysis-actions"')

  const labels = ['Repertoire', 'Saved variations', 'Stockfish', 'Lichess Explorer']
  const positions = labels.map(label => html.indexOf(`aria-label="${label}"`))
  expect(positions.every(position => position > -1)).toBe(true)
  expect(positions).toEqual([...positions].sort((a, b) => a - b))
  expect(html).toContain('aria-expanded="false"><span>Playlists</span>')
  expect(html).toContain('class="slot-playlist"')
  expect(html).not.toContain('analysis-slot slot-playlist')
  expect(html).toContain('class="board-heading"')
  expect(html).toContain('>Generate Playlist</button>')
  expect(html).toContain('Create a playlist from existing descendants of the current position')
  expect(html).toContain('Playing:')
  expect(html).toContain('aria-label="Analysis tools"')
  expect(html).toContain('aria-label="Line moves"')
  expect(html).toContain('Explore deeper plans')
  expect(html).not.toContain('aria-label="Planner"')
  expect(html).not.toContain('aria-label="Analysis panels"')
  savedSections = JSON.stringify({ line: false, playlist: true, engine: false, planner: true, explorer: true })
  const restored = renderToStaticMarkup(<App />)
  expect(restored).toContain('aria-expanded="false"><span>Repertoire</span>')
  expect(restored).toContain('aria-expanded="true"><span>Playlists</span>')
  expect(restored).toContain('aria-expanded="false"><span>Stockfish</span>')
  expect(restored).not.toContain('aria-label="Planner"')
  expect(restored).toContain('aria-expanded="true"><span>Lichess Explorer</span>')
  vi.unstubAllGlobals()
})
